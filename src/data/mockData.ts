export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

export function findNearestAuthorityBranch(
  lat: number,
  lng: number,
  governorateId?: string,
  cityDistrict?: string
): { branch: AuthorityBranch; distanceKm: number } {
  let bestBranch = AUTHORITY_BRANCHES[0];
  let minEffectiveDist = Infinity;

  for (const branch of AUTHORITY_BRANCHES) {
    const rawDist = calculateDistanceKm(lat, lng, branch.lat, branch.lng);
    let effectiveDist = rawDist;

    // District-level exact affinity (e.g. الأربعين, السويس, فيصل, مدينة نصر)
    if (cityDistrict) {
      const normInput = cityDistrict.trim().toLowerCase();
      const normBranchDist = branch.district.trim().toLowerCase();
      if (normInput.includes(normBranchDist) || normBranchDist.includes(normInput)) {
        effectiveDist = effectiveDist * 0.15;
      }
    }

    // Governorate-level affinity
    if (governorateId && branch.governorateId === governorateId) {
      effectiveDist = effectiveDist * 0.6;
    }

    if (effectiveDist < minEffectiveDist) {
      minEffectiveDist = effectiveDist;
      bestBranch = branch;
    }
  }

  const realDist = calculateDistanceKm(lat, lng, bestBranch.lat, bestBranch.lng);
  return { branch: bestBranch, distanceKm: realDist };
}

